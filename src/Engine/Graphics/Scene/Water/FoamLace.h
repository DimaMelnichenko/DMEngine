#pragma once

#include <cstdint>
#include <vector>
#include <DirectXMath.h>

namespace GS
{

// Узор пены — «кружево» (docs/water.md, «Пена»): пена ручья — не сплошной лист, а тонкие стенки пузырей, сгустки и мелкие
// пузырьки, и течение тянет её в нити, а не в гладкие ленты (так переносу течением подходят статистически однородные
// текстуры с мелкими деталями — Neyret, «Advected Textures», 2003). Основа — бесшовный шум Ворлея (стенки ячеек
// F2 − F1) на искривлённой шумом сетке: крупное кружево с рваными стенками разной толщины, сеть помельче и мелкая пена
// пузырьков там, где пены много (плотность — плавный шум). Бесшовная карта size², каналы — как у прежней текстуры пены
// (Tools/pack_water_foam.py): R — маска 0…1, выровненная по гистограмме (порог 1 − доля пены оставляет ту же долю площади:
// при малой доле — стыки стенок и сгустки, при полной — белая вода), G, B — нормаль по маске (0,5 + 0,5 · n, x и y в
// координатах карты), A — шум растворения, равномерно 0…1. Одинакова при том же seed
std::vector<DirectX::XMFLOAT4> generateFoamLace( uint32_t size, uint32_t seed );

// Густая пена — белая вода сливов и котлов под ступенями (второй слой узора пены: где её доля велика, кружево переходит в
// неё): плотно уложенные пузыри разного размера — стенки шума Ворлея в три октавы, мельче кружева, с плавными пятнами
// плотности. Каналы — как у кружева; маска выровнена по гистограмме, но не 0…1, а denseFoamGap…1: просветы у густой пены —
// тонкая пена, а не вода (при большой доле пены порог её пропускает — белая вода с пузырями)
constexpr float denseFoamGap = 0.35f;
std::vector<DirectX::XMFLOAT4> generateFoamDense( uint32_t size, uint32_t seed );

}
